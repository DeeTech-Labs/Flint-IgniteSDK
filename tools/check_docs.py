#!/usr/bin/env python3
"""Validate local documentation, canonical registry tables and maintained examples."""
from __future__ import annotations
import argparse
import copy
import importlib.util
import json
import re
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
REPOSITORIES = ('Flint-IgniteSDK', 'FlinT-OS', 'Flint-Flare')
LINK = re.compile(r'\]\((<[^>]+>|[^\s)]+)(?:\s+"[^"]*")?\)|\b(?:href|src)=["\']([^"\']+)["\']')
FENCE = re.compile(r'^(`{3,}|~{3,})([^\n]*)\n(.*?)^\1[^\n]*$', re.M | re.S)

def prose(text):
    return FENCE.sub(lambda m: '\n' * m.group().count('\n'), text)

def anchors(text):
    text = prose(text)
    result = set(re.findall(r'\b(?:id|name)=["\']([^"\']+)["\']', text))
    counts = {}
    for title in re.findall(r'^#{1,6}\s+(.+?)\s*#*\s*$', text, re.M):
        title = re.sub(r'<[^>]+>', '', title)
        slug = re.sub(r'[^\w\- ]', '', title.lower()).replace(' ', '-')
        count = counts.get(slug, 0)
        counts[slug] = count + 1
        result.add(f'{slug}-{count}' if count else slug)
    return result

def documents(root):
    files = set(root.glob('*.md')) | set((root/'docs').rglob('*.md'))
    for folder in ('examples', '.github'):
        files.update((root/folder).rglob('*.md'))
    return sorted(files)

def target_for(source, url, repositories):
    parts = urlsplit(url.strip('<>'))
    if parts.scheme or parts.netloc:
        bits = parts.path.strip('/').split('/')
        if (parts.netloc == 'github.com' and len(bits) >= 5 and
                bits[0] == 'DeeTech-Labs' and bits[1] in repositories and
                bits[2:4] in (['blob','main'], ['tree','main'])):
            return repositories[bits[1]] / unquote('/'.join(bits[4:])), unquote(parts.fragment)
        return None, ''  # Remote reachability/publication is intentionally not asserted.
    return ((source.parent/unquote(parts.path)).resolve() if parts.path else source), unquote(parts.fragment)

def check_links(root, repositories):
    errors = []
    for source in documents(root):
        text = source.read_text(encoding='utf-8')
        if '\ufffd' in text:
            errors.append(f'{source}: Unicode replacement character')
        content = prose(text)
        opened = None
        for number, line in enumerate(text.splitlines(), 1):
            fence = re.match(r'^(`{3,}|~{3,})(.*)$', line)
            if not fence:
                continue
            mark, suffix = fence.groups()
            if opened is None:
                opened = (mark, number)
            elif mark[0] == opened[0][0] and len(mark) >= len(opened[0]) and not suffix.strip():
                opened = None
        if opened:
            errors.append(f'{source}:{opened[1]}: unclosed Markdown fence')
        # Reference-style links are navigation too, even when the usage is elsewhere.
        urls = [(m.start(), next(v for v in m.groups() if v is not None)) for m in LINK.finditer(content)]
        urls += [(m.start(), m.group(1)) for m in re.finditer(r'^\s*\[[^\]]+\]:\s*(\S+)', content, re.M)]
        for offset, url in urls:
            target, fragment = target_for(source, url, repositories)
            if target is None:
                continue
            line = content[:offset].count('\n')+1
            if not target.exists():
                errors.append(f'{source}:{line}: missing {url}')
            elif fragment and target.suffix.lower() == '.md' and fragment not in anchors(target.read_text(encoding='utf-8')):
                errors.append(f'{source}:{line}: missing anchor {url}')
        for match in FENCE.finditer(text):
            language = match.group(2).strip().lower()
            try:
                if language == 'toml':
                    tomllib.loads(match.group(3))
                elif language == 'json':
                    json.loads(match.group(3))
            except (ValueError, tomllib.TOMLDecodeError) as error:
                errors.append(f'{source}:{text[:match.start()].count(chr(10))+1}: invalid {language} fence: {error}')
    return errors

def registry_document(root, language):
    services = json.loads((root/'spec/services.json').read_text(encoding='utf-8'))['services']
    permissions = json.loads((root/'spec/permissions.json').read_text(encoding='utf-8'))
    contract = (root/'include/flint/contracts.h').read_text(encoding='utf-8')
    revision = re.search(r'ContractRevision\s*=\s*(0x[0-9a-fA-F]+)', contract).group(1)
    enum = re.search(r'enum class Error[^\{]*\{([^}]+)', contract).group(1)
    errors = re.findall(r'^\s*([a-z_]+)\s*,?\s*$', enum, re.M)
    ru = language == 'ru'
    lines = ['# Registry: '+ ('контракты, не обещания backend' if ru else 'contracts, not backend promises'), '',
        '<!-- Generated by tools/check_docs.py --write-registry; do not edit tables. -->', '',
        ('[Индекс](README.md) · [English](../en/REGISTRY.md)' if ru else '[Index](INDEX.md) · [Canonical Russian](../ru/REGISTRY.md)'), '',
        f'ContractRevision `{revision}`.', '',
        ('Источник таблиц: spec/services.json, spec/permissions.json и contracts.h. Наличие имени '
         'не подтверждает реализованный API, hardware или право доступа. Рабочие Lua-вызовы '
         'и ограничения описаны в [Lua API](LUA-API.md); wire — в [архитектуре](ARCHITECTURE.md), '
         '[sensors](SENSORS.md), [services](BACKGROUND-SERVICES.md).'
         if ru else 'Tables derive from spec/services.json, spec/permissions.json and contracts.h. '
         'Registration does not prove an implemented API, hardware or authorization. '
         '[Lua API](LUA-API.md) documents actual calls; [architecture](ARCHITECTURE.md), '
         '[sensors](SENSORS.md), [services](BACKGROUND-SERVICES.md) own wire details.'), '',
        '## Error', '', '| Code | Identifier |', '| ---: | --- |']
    lines += [f'| {i} | `{name}` |' for i,name in enumerate(errors)]
    lines += ['', '## Companion methods', '', '| ID | Name | Mutates | Trust |', '| ---: | --- | --- | --- |']
    lines += [f'| {s["id"]} | `{s["name"]}` | {str(s["mutates"]).lower()} | {s.get("trust","unspecified")} |' for s in services]
    for category, names in permissions.items():
        if category == 'version': continue
        lines += ['', f'## {category}', '', '| Permission |', '| --- |']
        lines += [f'| `{name}` |' for name in names]
    return '\n'.join(lines)+'\n'

def check_registry(root, write=False):
    errors=[]
    for language in ('ru','en'):
        path=root/f'docs/{language}/REGISTRY.md'
        expected=registry_document(root, language)
        if write:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(expected,encoding='utf-8')
        elif not path.exists() or path.read_text(encoding='utf-8') != expected:
            errors.append(f'{path}: stale; run python tools/check_docs.py --write-registry')
    return errors

def check_model_fences(os_root):
    """Validate documented TOML overrides with the owning OS generator's real schema."""
    module_spec = importlib.util.spec_from_file_location('flint_doc_device', os_root/'tools/select_device.py')
    module = importlib.util.module_from_spec(module_spec)
    module_spec.loader.exec_module(module)
    baseline = tomllib.loads((os_root/'config/devices/flint_spark/device.toml').read_text(encoding='utf-8'))
    def merge(target, values):
        for key,value in values.items():
            if isinstance(value,dict) and isinstance(target.get(key),dict): merge(target[key],value)
            else: target[key]=copy.deepcopy(value)
    errors=[]
    original=module.read_toml
    for source in documents(os_root):
        for match in FENCE.finditer(source.read_text(encoding='utf-8')):
            if match.group(2).strip() != 'toml': continue
            try:
                override=tomllib.loads(match.group(3))
                if not set(override).intersection(('modules','background')): continue
                selected=copy.deepcopy(baseline);merge(selected,override)
                module.read_toml=lambda _: selected
                module.load_device(os_root/'config/devices/flint_spark/device.toml')
            except (ValueError,OSError) as error:
                errors.append(f'{source}: TOML example rejected by OS schema: {error}')
            finally:
                module.read_toml=original
    return errors

def check_examples(root, validator, runner):
    # Imports remain the authoritative compiler; never introduce a documentation-only schema.
    sys.path.insert(0,str(root/'tools'))
    from compile_ignite import compile_project
    from ignite import scenario_script
    errors=[]
    (root/'temp').mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='docs-examples-',dir=root/'temp') as directory:
        work=Path(directory)
        factory=work/'factory';factory.mkdir()
        for source in sorted((root/'system').glob('*.json'))+sorted((root/'examples').glob('*/project.json')):
            try:
                data=compile_project(json.loads(source.read_text(encoding='utf-8')),source.parent)
                output=factory/(source.stem+'.ignit') if source.parent.name=='system' else work/(source.parent.name+'.ignit')
                output.write_bytes(data)
                if validator:
                    subprocess.run([str(validator),str(output)],check=True,capture_output=True,text=True,encoding='utf-8',timeout=30)
            except (OSError, ValueError, subprocess.SubprocessError) as error:
                errors.append(f'{source}: {getattr(error,"stderr",None) or str(error)}');continue
            scenario=source.parent/'scenario.json'
            if source.name=='project.json' and scenario.exists():
                try:
                    scenario_script(scenario)
                    if runner:
                        subprocess.run([sys.executable,'-B',str(root/'tools/ignite.py'),'run',str(output),
                            '--runner',str(runner),'--scenario',str(scenario),'--factory',str(factory),
                            '--image',str(work/(source.parent.name+'.ppm'))],check=True,capture_output=True,text=True,encoding='utf-8',timeout=40)
                except (OSError,ValueError,subprocess.SubprocessError) as error:
                    detail=getattr(error,'stderr',None) or str(error)
                    errors.append(f'{scenario}: {detail}')
    return errors

def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo',type=Path,default=ROOT)
    parser.add_argument('--ecosystem',type=Path,help='parent of all three owning checkouts; checks cross-repository GitHub main links locally')
    parser.add_argument('--write-registry',action='store_true')
    parser.add_argument('--examples',action='store_true')
    parser.add_argument('--validator',type=Path)
    parser.add_argument('--runner',type=Path)
    args=parser.parse_args(argv)
    repositories={}
    roots=[args.repo.resolve()]
    if args.ecosystem:
        repositories={name:args.ecosystem.resolve()/name for name in REPOSITORIES}
        roots=list(repositories.values())
    errors=check_registry(ROOT,args.write_registry)
    for root in roots:
        if not (root/'README.md').exists():
            errors.append(f'{root}: missing owning checkout');continue
        errors.extend(check_links(root,repositories))
    if args.ecosystem and repositories['FlinT-OS'].exists():
        errors.extend(check_model_fences(repositories['FlinT-OS']))
    if args.examples:
        errors.extend(check_examples(ROOT,args.validator.resolve() if args.validator else None,args.runner.resolve() if args.runner else None))
    if errors:
        print('\n'.join(errors));return 1
    print(f'Documentation OK: {sum(len(documents(r)) for r in roots)} Markdown files; local links/anchors/config fences and SDK registry. Remote publication/hardware not checked.')
    return 0

if __name__=='__main__':
    raise SystemExit(main())
